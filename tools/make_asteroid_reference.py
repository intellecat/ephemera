#!/usr/bin/env python3
"""Regenerate tests/asteroid_ref.h from JPL Horizons (development only).

Horizons' own "apparent ecliptic of date" output uses the IAU-1976/1980
reduction, so instead we fetch light-time corrected geocentric ICRF vectors
(VEC_CORR='LT') plus the Earth's heliocentric and barycentric states, apply
solar light deflection and aberration with ERFA, and reduce with the
IAU-2006/2000A precession-nutation, as tools/make_reference.py does for the
planets.  Times are UT, so the test also exercises Delta-T.

    python3 -m venv /tmp/eph && /tmp/eph/bin/pip install pyerfa numpy
    /tmp/eph/bin/python tools/make_asteroid_reference.py
"""
import math
import os
import urllib.parse
import urllib.request

import erfa
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J2000 = 2451545.0
AU_PER_LIGHT_DAY = 173.1446326846693

# (eph_body id, Horizons command)
BODIES = [(11, "1;"), (12, "2;"), (13, "3;"), (14, "4;")]
# (JD UT, fractional year for Delta-T): 0h UT on 1900-01-01, 1930-07-01,
# 1960-01-01, 2000-01-01, 2026-01-01, 2050-01-01.
DATES = [(2415020.5, 1900.041667), (2426142.5, 1930.458333),
         (2436934.5, 1960.041667), (2451544.5, 2000.041667),
         (2461041.5, 2026.041667), (2469807.5, 2050.041667)]


def horizons(cmd, center, corr, jds, table="1"):
    """ICRF vectors (AU, AU/day); rows of 3 (table 1) or 6 (table 2)."""
    params = {
        "format": "text", "COMMAND": f"'{cmd}'", "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'", "EPHEM_TYPE": "'VECTORS'",
        "CENTER": f"'{center}'", "REF_PLANE": "'FRAME'",
        "REF_SYSTEM": "'ICRF'", "VEC_CORR": f"'{corr}'",
        "OUT_UNITS": "'AU-D'", "VEC_TABLE": f"'{table}'",
        "CSV_FORMAT": "'YES'", "TIME_TYPE": "'UT'",
        "TLIST_TYPE": "'JD'", "TLIST": " ".join(f"'{j}'" for j in jds),
    }
    url = "https://ssd.jpl.nasa.gov/api/horizons.api?" + urllib.parse.urlencode(
        params)
    with urllib.request.urlopen(url, timeout=120) as r:
        text = r.read().decode("utf-8", "replace")
    body = text[text.find("$$SOE") + 5:text.find("$$EOE")].strip()
    out = []
    for ln in body.splitlines():
        f = [x.strip() for x in ln.split(",")]
        out.append(np.array([float(x) for x in f[2:8 if table == "2" else 5]]))
    return out


def apparent(geo_lt, earth_helio, earth_bary):
    """Light-time corrected geocentric vector -> apparent unit direction:
    solar deflection (finite distance) then annual aberration."""
    p = geo_lt / np.linalg.norm(geo_lt)
    q = earth_helio + geo_lt
    em = np.linalg.norm(earth_helio)
    p = erfa.ld(1.0, p, q / np.linalg.norm(q), earth_helio / em, em, 1e-9)
    v = earth_bary[3:] / AU_PER_LIGHT_DAY
    return erfa.ab(p, v, em, math.sqrt(1.0 - v @ v))


def ecliptic_of_date(v, jd_tt):
    dt = jd_tt - J2000
    v = erfa.pnm06a(J2000, dt) @ (v / np.linalg.norm(v))
    _, deps = erfa.nut06a(J2000, dt)
    eps = erfa.obl06(J2000, dt) + deps
    y = v[1] * math.cos(eps) + v[2] * math.sin(eps)
    z = -v[1] * math.sin(eps) + v[2] * math.cos(eps)
    return math.degrees(math.atan2(y, v[0])) % 360.0, math.degrees(math.asin(z))


def main():
    jds = [jd for jd, _ in DATES]
    earth_helio = horizons("399", "500@10", "NONE", jds)
    earth_bary = horizons("399", "500@0", "NONE", jds, table="2")
    rows = []
    for body, cmd in BODIES:
        geo = horizons(cmd, "500@399", "LT", jds)
        for (jd, year), g, eh, eb in zip(DATES, geo, earth_helio, earth_bary):
            v = apparent(g, eh, eb)
            # UT instead of TT only orients the precession-nutation; the
            # ~70 s difference changes it by ~0.0001".
            lon, lat = ecliptic_of_date(v, jd)
            rows.append((body, jd, year, lon, lat))

    out = os.path.join(ROOT, "tests", "asteroid_ref.h")
    with open(out, "w") as f:
        f.write("/* Generated by tools/make_asteroid_reference.py from JPL "
                "Horizons:\n * apparent geocentric ecliptic of date, "
                "IAU-2006/2000A. */\n")
        f.write("#pragma once\n")
        f.write("struct AstRef { int body; double jd_ut, year, lon_deg, "
                "lat_deg; };\n\n")
        f.write(f"static const AstRef kAstRef[{len(rows)}] = {{\n")
        for r in rows:
            f.write("    {%d, %.6f, %.6f, %.8f, %.8f},\n" % r)
        f.write("};\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
