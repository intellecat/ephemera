#!/usr/bin/env python3
"""Regenerate tests/lahiri_ref.h (development only): the official Lahiri
ayanamsa from the Indian Astronomical Ephemeris (Positional Astronomy
Centre, India Meteorological Department; free downloads at
http://www.packolkata.gov.in/download/IAE<year>.zip), the table "True
ayanamsa for 5h 29m.0 I.S.T." every three days.  The IAE defines

    Mean ayanamsa = 23 51' 25".53 + precession in longitude from 2000.0
    True ayanamsa = mean ayanamsa + nutation in longitude

Needs pypdf.  Pass the extracted PDFs:

    python3 tools/make_lahiri_reference.py "IAE 2019.pdf" "IAE 2026.pdf"
"""
import os
import re
import sys

from pypdf import PdfReader

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MONTHS = {"Jan": 1, "Feb": 2, "Mar": 3, "Apr": 4, "May": 5, "June": 6,
          "July": 7, "Aug": 8, "Sept": 9, "Oct": 10, "Nov": 11, "Dec": 12}


def julian_day(y, m, d):
    if m <= 2:
        y, m = y - 1, m + 12
    a = y // 100
    return int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + d + 2 - a + a // 4 - 1524.5


def table(path):
    """(JD UT, ayanamsa in arcseconds) from the edition's ayanamsa page."""
    reader = PdfReader(path)
    for page in reversed(reader.pages):
        text = page.extract_text() or ""
        if "TRUE  AYANAMSA" in text or "TRUE AYANAMSA" in text:
            break
    else:
        raise SystemExit("no ayanamsa table in " + path)
    year = int(re.search(r"AYANAMSA,\s*(\d{4})", text).group(1))
    lines = text.splitlines()
    start = next(i for i, ln in enumerate(lines) if ln.startswith("Jan. 1"))
    # Four columns per line: [month] day deg min sec; columns run down the
    # page, so remember the current month per column.
    month = [None] * 4
    last_day = [0] * 4
    year_of = [year] * 4
    rows = []
    for ln in lines[start:]:
        tokens = ln.replace("Dec.27", "Dec. 27").replace("Aug.29", "Aug. 29").split()
        col, i = 0, 0
        while i < len(tokens) and col < 4:
            t = tokens[i].rstrip(".")
            if t in MONTHS:
                if month[col] is not None and MONTHS[t] < month[col]:
                    year_of[col] += 1
                month[col] = MONTHS[t]
                i += 1
            if len(tokens) < i + 4 or not re.fullmatch(r"\d+\.\d", tokens[i + 3]):
                break
            day, deg, mi, sec = tokens[i:i + 4]
            if int(day) < last_day[col] and t not in MONTHS:
                # The month label went to another line in the PDF text.
                month[col] += 1
                if month[col] > 12:
                    month[col], year_of[col] = 1, year_of[col] + 1
            last_day[col] = int(day)
            # 5h 29m IST = 23h 59m UT of the previous day.
            jd = julian_day(year_of[col], month[col], int(day)) - 1.0 / 1440.0
            rows.append((jd, int(deg) * 3600 + int(mi) * 60 + float(sec)))
            i += 4
            col += 1
        if col == 0:
            break
    return year, sorted(set(rows))


# Entries that contradict the edition's own definition (mean ayanamsa +
# nutation): IAE 2026 lists 2027-02-13 .. 2027-04-26 about 4.6" low, a
# jump of 4.5" in three days where nutation moves < 0.2".
MISPRINTS = [(julian_day(2027, 2, 13) - 0.01, julian_day(2027, 4, 27))]


def main():
    editions = [(y, [r for r in rows if not any(a <= r[0] < b for a, b in MISPRINTS)])
                for y, rows in (table(p) for p in sys.argv[1:])]
    with open(os.path.join(ROOT, "tests", "lahiri_ref.h"), "w") as f:
        f.write("/* Generated by tools/make_lahiri_reference.py: the true Lahiri ayanamsa\n"
                " * (arcseconds, 0.1\" rounding) at JD UT from the Indian Astronomical\n"
                " * Ephemeris, editions %s (Positional Astronomy Centre, IMD). */\n"
                % ", ".join(str(y) for y, _ in editions))
        f.write("#pragma once\n\nstruct LahiriRef { double jd_ut, arcsec; };\n"
                "static const LahiriRef kLahiriRef[] = {\n")
        for _, rows in editions:
            for jd, a in rows:
                f.write("    {%.6f, %.1f},\n" % (jd, a))
        f.write("};\n")
    print(", ".join("%d: %d values" % (y, len(r)) for y, r in editions))


if __name__ == "__main__":
    main()
