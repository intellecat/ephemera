#!/usr/bin/env python3
"""Regenerate tests/minor_ref.h (development only): apparent geocentric RA
and Dec (true equator and equinox of date, airless) of sample minor
planets from JPL Horizons at random dates, TT.  One date per request:
Horizons integrates through all the dates of a request in time order, and
for chaotic bodies (Apophis) that path changes the result.

    python3 tools/make_minor_reference.py 1 10 433 1181 1566 5145 99942 136199
"""
import os
import sys
import urllib.parse
import urllib.request

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def observer(num, jds):
    q = urllib.parse.urlencode({
        "format": "text", "COMMAND": "'%d;'" % num, "CENTER": "'500@399'",
        "EPHEM_TYPE": "OBSERVER", "QUANTITIES": "'2'", "ANG_FORMAT": "DEG",
        "EXTRA_PREC": "YES", "CSV_FORMAT": "YES", "TIME_TYPE": "TT",
        "TLIST": " ".join("'%.6f'" % j for j in jds)})
    with urllib.request.urlopen("https://ssd.jpl.nasa.gov/api/horizons.api?" + q,
                                timeout=180) as r:
        t = r.read().decode()
    rows = t[t.index("$$SOE") + 5:t.index("$$EOE")].strip().splitlines()
    out = []
    for row in rows:
        f = [x.strip() for x in row.split(",")]
        nums = [x for x in f[1:] if x and x.replace(".", "", 1).replace("-", "", 1).isdigit()]
        out.append((float(nums[0]), float(nums[1])))
    return out


def main():
    rng = np.random.default_rng(7)
    rows = []
    for num in [int(x) for x in sys.argv[1:]]:
        jds = sorted(rng.uniform(2415100, 2487900, 5))
        for jd in jds:
            ra, dec = observer(num, [jd])[0]
            rows.append((num, jd, ra, dec))
    with open(os.path.join(ROOT, "tests", "minor_ref.h"), "w") as f:
        f.write("/* Generated by tools/make_minor_reference.py: apparent geocentric RA, Dec\n"
                " * (degrees, true equator of date) from JPL Horizons, JD TT. */\n"
                "#pragma once\n\nstruct MinorRef { int number; double jd, ra, dec; };\n"
                "static const MinorRef kMinorRef[] = {\n")
        for r in rows:
            f.write("    {%d, %.6f, %.9f, %.9f},\n" % r)
        f.write("};\n")
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
