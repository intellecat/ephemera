#!/usr/bin/env python3
"""Emit tests/reference_data.h from a JSON reference file.

The JSON is produced (test-only, never shipped) with Skyfield + a JPL DE
kernel; see tools/make_reference.py.  It supplies geometric and apparent
geocentric ecliptic-of-date longitudes/latitudes/distances that the
analytical engine is validated against.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BODY_INDEX = {
    "Mercury": 0, "Venus": 1, "Earth": 2, "Mars": 3, "Jupiter": 4,
    "Saturn": 5, "Uranus": 6, "Neptune": 7, "Pluto": 8, "Sun": 9, "Moon": 10,
}


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/tmp/opencode/ref.json"
    with open(src) as f:
        ref = json.load(f)

    jds = [d["tt_jd"] for d in ref["dates"]]
    rows = []
    for name, samples in ref["bodies"].items():
        body = BODY_INDEX[name]
        for jd, s in zip(jds, samples):
            rows.append((body, jd, s))

    out = os.path.join(ROOT, "tests", "reference_data.h")
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_reference.py -- do not edit. */\n")
        f.write("#pragma once\n\n")
        f.write("struct RefSample {\n")
        f.write("    int body;\n    double tt_jd;\n")
        f.write("    double geom_lon, geom_lat, geom_dist;\n")
        f.write("    double app_lon, app_lat, app_dist;\n")
        f.write("};\n\n")

        f.write(f"static const RefSample kRefSamples[{len(rows)}] = {{\n")
        for body, jd, s in rows:
            f.write(
                "    {%d, %.11f, %.12f, %.12f, %.12f, %.12f, %.12f, %.12f},\n"
                % (body, jd, s["geom_lon"], s["geom_lat"], s["geom_dist"],
                   s["app_lon"], s["app_lat"], s["app_dist"])
            )
        f.write("};\n")
    print("wrote", out, len(rows), "samples")


if __name__ == "__main__":
    main()
