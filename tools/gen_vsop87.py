#!/usr/bin/env python3
"""Generate embedded C++ coefficient tables from the VSOP87D data files.

The VSOP87D solution expresses heliocentric spherical coordinates
(longitude L, latitude B, radius R) of the planets directly in the
dynamical ecliptic and equinox of date, which is the frame used by
tropical astrology.

Each coordinate is a Poisson series

    C(t) = sum_{alpha=0..5} T**alpha * sum_i A_i * cos(B_i + C_i * T)

with T measured in thousands of Julian years from J2000.

This script downloads the original IMCCE files (once) into
data/vsop87d/ and emits data/vsop87d_data.{h,cpp}.

Usage:
    python3 tools/gen_vsop87.py [--truncate-arcsec X]
"""

from __future__ import annotations

import argparse
import os
import sys
import urllib.request

BASE_URL = "https://ftp.imcce.fr/pub/ephem/planets/vsop87"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RAW_DIR = os.path.join(ROOT, "data", "vsop87d")
OUT_DIR = os.path.join(ROOT, "data")

# Body order must match eph_body in include/ephemeris/ephemeris.h
PLANETS = [
    ("MERCURY", "mer"),
    ("VENUS", "ven"),
    ("EARTH", "ear"),
    ("MARS", "mar"),
    ("JUPITER", "jup"),
    ("SATURN", "sat"),
    ("URANUS", "ura"),
    ("NEPTUNE", "nep"),
]

MAX_ALPHA = 5


def download(name: str) -> str:
    os.makedirs(RAW_DIR, exist_ok=True)
    path = os.path.join(RAW_DIR, name)
    if not os.path.exists(path):
        url = f"{BASE_URL}/{name}"
        sys.stderr.write(f"downloading {url}\n")
        with urllib.request.urlopen(url, timeout=120) as r, open(path, "wb") as f:
            f.write(r.read())
    return path


def parse(path: str):
    """Return series[coord][alpha] = list of (A, B, C). coord: L=0,B=1,R=2."""
    series = [[[] for _ in range(MAX_ALPHA + 1)] for _ in range(3)]
    with open(path, "r") as f:
        for line in f:
            if "VSOP87" in line:
                continue
            if len(line) < 131:
                continue
            # Term record (1-indexed Fortran columns from vsop87.doc):
            #   col 4  : coordinate index (1=L, 2=B, 3=R)
            #   col 5  : alpha (power of T)
            #   col 80-97  : A
            #   col 98-111 : B
            #   col 112-131: C
            try:
                ic = int(line[3])
                it = int(line[4])
                A = float(line[79:97])
                B = float(line[97:111])
                C = float(line[111:131])
            except ValueError:
                # malformed/blank line
                continue
            if not (1 <= ic <= 3 and 0 <= it <= MAX_ALPHA):
                continue
            series[ic - 1][it].append((A, B, C))
    return series


def c_float(x: float) -> str:
    # repr() round-trips; ensure the literal is a valid double and contains a dot/exponent.
    s = repr(x)
    if "e" not in s and "E" not in s and "." not in s:
        s += ".0"
    return s


def emit(planets_data):
    os.makedirs(OUT_DIR, exist_ok=True)

    header = os.path.join(OUT_DIR, "vsop87d_data.h")
    source = os.path.join(OUT_DIR, "vsop87d_data.cpp")

    with open(header, "w") as h:
        h.write(
            "/* Generated by tools/gen_vsop87.py -- do not edit by hand. */\n"
            "#pragma once\n\n"
            "namespace eph {\nnamespace vsop87d {\n\n"
            "struct Term { double a; double b; double c; };\n"
            "struct Series { const Term* terms; int count; };\n"
            "struct Body {\n"
            "    const Series* l; int nl;\n"
            "    const Series* b; int nb;\n"
            "    const Series* r; int nr;\n"
            "};\n\n"
            "extern const Body bodies[8];\n\n"
            "}  // namespace vsop87d\n}  // namespace eph\n"
        )

    with open(source, "w") as s:
        s.write(
            "/* Generated by tools/gen_vsop87.py -- do not edit by hand. */\n"
            '#include "vsop87d_data.h"\n\n'
            "namespace eph {\nnamespace vsop87d {\n\n"
        )

        body_entries = []
        for name in planets_data:
            for coord, cname in ((0, "L"), (1, "B"), (2, "R")):
                series_list = []
                for alpha in range(MAX_ALPHA + 1):
                    terms = planets_data[name]["series"][coord][alpha]
                    arr = f"{name}_{cname}{alpha}"
                    if terms:
                        s.write(f"static const Term {arr}[] = {{\n")
                        for a, b, c in terms:
                            s.write(f"    {{{c_float(a)}, {c_float(b)}, {c_float(c)}}},\n")
                        s.write("};\n")
                        series_list.append((arr, len(terms)))
                    else:
                        series_list.append(("nullptr", 0))
                    s.write("\n")
                s.write(f"static const Series {name}_{cname}[] = {{\n")
                for arr, n in series_list:
                    s.write(f"    {{{arr}, {n}}},\n")
                s.write("};\n\n")
            body_entries.append(
                f"    {{{name}_L, {MAX_ALPHA + 1}, {name}_B, {MAX_ALPHA + 1}, "
                f"{name}_R, {MAX_ALPHA + 1}}},\n"
            )

        s.write("const Body bodies[8] = {\n")
        for e in body_entries:
            s.write(e)
        s.write("};\n\n")
        s.write("}  // namespace vsop87d\n}  // namespace eph\n")

    return header, source


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--truncate-arcsec",
        type=float,
        default=None,
        help="Drop angular terms whose amplitude is below this many arcseconds.",
    )
    args = ap.parse_args()

    planets_data = {}
    for name, ext in PLANETS:
        fname = f"VSOP87D.{ext}"
        path = download(fname)
        series = parse(path)
        n = sum(len(series[c][a]) for c in range(3) for a in range(MAX_ALPHA + 1))
        sys.stderr.write(f"{fname}: {n} terms\n")
        planets_data[name] = {"series": series}

    header, source = emit(planets_data)
    sys.stderr.write(f"wrote {header}\nwrote {source}\n")


if __name__ == "__main__":
    main()
