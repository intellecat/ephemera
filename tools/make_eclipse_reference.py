#!/usr/bin/env python3
"""Regenerate tests/eclipse_ref.h (development only): solar and lunar
eclipses 1850-2150 from Swiss Ephemeris (pyswisseph with the sepl/semo
files: SE_EPHE_PATH), global and local circumstances, times in TT.  Test
data only; no code is shared.

    SE_EPHE_PATH=... python3 tools/make_eclipse_reference.py
"""
import os

import swisseph as swe

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = swe.julday(1850, 1, 1), swe.julday(2150, 1, 1)
# Places for the local circumstances: (east longitude, latitude, metres).
PLACES = [(-104.15, 25.29, 0.0), (13.40, 52.52, 34.0), (116.40, 39.90, 44.0),
          (-70.65, -33.45, 570.0), (151.21, -33.87, 20.0)]
FLAGS = swe.FLG_SWIEPH


def tt(ut):
    return ut + swe.deltat(ut) if ut > 0 else 0.0


def kind(res):
    """Swiss Ephemeris type bits -> EPH_ECLIPSE_* flags."""
    out = 0
    if res & swe.ECL_ANNULAR_TOTAL:
        out = 4
    elif res & swe.ECL_TOTAL:
        out = 1
    elif res & swe.ECL_ANNULAR:
        out = 2
    elif res & swe.ECL_PARTIAL:
        out = 8
    elif res & swe.ECL_PENUMBRAL:
        out = 16
    if out in (1, 2, 4) and res & swe.ECL_NONCENTRAL:
        out |= 32
    return out


def main():
    swe.set_ephe_path(os.environ.get("SE_EPHE_PATH"))
    solar, lunar, local = [], [], []
    t = START
    while True:
        res, r = swe.sol_eclipse_when_glob(t, FLAGS)
        if r[0] > END:
            break
        pos = swe.sol_eclipse_where(r[0], FLAGS)
        attr = swe.sol_eclipse_how(r[0], (pos[1][0], pos[1][1], 0.0), FLAGS)[1]
        solar.append((kind(res), tt(r[0]), tt(r[2]), tt(r[3]), tt(r[4]), tt(r[5]),
                      tt(r[6]), tt(r[7]), pos[1][1], pos[1][0], attr[8],
                      int(attr[9])))
        t = r[0] + 20
    t = START
    while True:
        res, r = swe.lun_eclipse_when(t, FLAGS)
        if r[0] > END:
            break
        attr = swe.lun_eclipse_how(r[0], (0.0, 0.0, 0.0), FLAGS)[1]
        lunar.append((kind(res), tt(r[0]), tt(r[6]), tt(r[7]), tt(r[2]), tt(r[3]),
                      tt(r[4]), tt(r[5]), attr[0], attr[1], int(attr[9])))
        t = r[0] + 20
    for k, (lon, lat, h) in enumerate(PLACES):
        t = swe.julday(1950 + 30 * k, 1, 1)
        for _ in range(4):
            res, r, attr = swe.sol_eclipse_when_loc(t, (lon, lat, h), FLAGS)
            local.append((k, kind(res), tt(r[0]), tt(r[1]), tt(r[2]), tt(r[3]),
                          tt(r[4]), attr[8], attr[2], attr[5]))
            t = r[0] + 20

    with open(os.path.join(ROOT, "tests", "eclipse_ref.h"), "w") as f:
        f.write("/* Generated by tools/make_eclipse_reference.py: Swiss Ephemeris "
                "eclipses (TT).  Test data only. */\n#pragma once\n\n")
        f.write("struct SolarRef { int type; double max, begin, end, central_begin, "
                "central_end, center_begin, center_end, lat, lon, mag; int saros; };\n")
        f.write("static const SolarRef kSolar[] = {\n")
        for r in solar:
            f.write("    {%d, %.6f, %.6f, %.6f, %.6f, %.6f, %.6f, %.6f, %.4f, %.4f, "
                    "%.5f, %d},\n" % r)
        f.write("};\n\nstruct LunarRef { int type; double max, pen_begin, pen_end, "
                "par_begin, par_end, tot_begin, tot_end, umag, pmag; int saros; };\n")
        f.write("static const LunarRef kLunar[] = {\n")
        for r in lunar:
            f.write("    {%d, %.6f, %.6f, %.6f, %.6f, %.6f, %.6f, %.6f, %.5f, %.5f, "
                    "%d},\n" % r)
        f.write("};\n\nstatic const double kPlaces[][3] = {\n")
        for p in PLACES:
            f.write("    {%.4f, %.4f, %.1f},\n" % p)
        f.write("};\n\nstruct LocalRef { int place, type; double max, c1, c2, c3, c4, "
                "mag, obscuration, altitude; };\nstatic const LocalRef kLocal[] = {\n")
        for r in local:
            f.write("    {%d, %d, %.6f, %.6f, %.6f, %.6f, %.6f, %.5f, %.5f, %.4f},\n" % r)
        f.write("};\n")
    print(len(solar), "solar,", len(lunar), "lunar,", len(local), "local")


if __name__ == "__main__":
    main()
