#!/usr/bin/env python3
"""Regenerate tests/orbit_ref.h (development only): osculating orbital
elements of the planets and Pluto from JPL DE440 with Skyfield
(osculating_elements_of, heliocentric, GM of the Sun plus the planet) in
the IAU 2006 mean ecliptic and equinox of date (ERFA ecm06), and the
geocentric longitudes of the four orbit points (nodes, perihelion,
aphelion) with ERFA nutation.

    DE440=/path/to/de440.bsp python3 tools/make_orbit_reference.py
"""
import os

import erfa
import numpy as np
from skyfield.api import load
from skyfield.elementslib import osculating_elements_of

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GM_SUN = 1.3271244004127942e11  # km^3/s^2, DE440
# eph_body, DE440 target, Sun / planet mass ratio
BODIES = [(0, "mercury barycenter", 6023657.33), (1, "venus barycenter", 408523.719),
          (3, "mars barycenter", 3098703.59), (4, "jupiter barycenter", 1047.348644),
          (5, "saturn barycenter", 3497.9018), (6, "uranus barycenter", 22902.944),
          (7, "neptune barycenter", 19412.26), (8, "pluto barycenter", 136045556.0)]


def main():
    eph = load(os.environ.get("DE440", "de440.bsp"))
    ts = load.timescale()
    sun, earth = eph["sun"], eph["earth"]
    rng = np.random.default_rng(31)
    rows = []
    for body, name, ratio in BODIES:
        for jd in rng.uniform(2305448, 2634167, 12):  # 1600-2500
            t = ts.tt_jd(jd)
            pos = (eph[name] - sun).at(t)
            # The frame: ICRS -> IAU 2006 mean ecliptic and equinox of date.
            rot = erfa.ecm06(2400000.5, jd - 2400000.5)
            el = osculating_elements_of(pos, rot, GM_SUN * (1.0 + 1.0 / ratio))
            a, e = el.semi_major_axis.au, el.eccentricity
            i, node = el.inclination.radians, el.longitude_of_ascending_node.radians
            peri = el.longitude_of_periapsis.radians
            # The four points, then geocentric with the Earth from DE440.
            w = peri - node
            n = np.array([np.cos(node), np.sin(node), 0.0])
            hu = np.array([np.sin(i) * np.sin(node), -np.sin(i) * np.cos(node), np.cos(i)])
            q = np.cross(hu, n)
            p = a * (1 - e * e)
            e_helio = rot @ (earth - sun).at(t).position.au
            dpsi = erfa.nut06a(2400000.5, jd - 2400000.5)[0]
            geo = []
            for u in (0.0, np.pi, w, w + np.pi):
                r = p / (1 + e * np.cos(u - w))
                g = (np.cos(u) * n + np.sin(u) * q) * r - e_helio
                geo.append(np.degrees((np.arctan2(g[1], g[0]) + dpsi) % (2 * np.pi)))
            rows.append((body, jd, a, e, np.degrees(i), np.degrees(node) % 360,
                         np.degrees(peri) % 360) + tuple(geo))
    with open(os.path.join(ROOT, "tests", "orbit_ref.h"), "w") as f:
        f.write("/* Generated by tools/make_orbit_reference.py: osculating elements from\n"
                " * DE440 (Skyfield, ERFA), mean ecliptic of date; degrees. */\n"
                "#pragma once\n\nstruct OrbitRef { int body; double jd, a, e, i, node, "
                "peri, geo[4]; };\nstatic const OrbitRef kOrbitRef[] = {\n")
        for r in rows:
            f.write("    {%d, %.6f, %.10f, %.10f, %.9f, %.9f, %.9f, {%.8f, %.8f, %.8f, %.8f}},\n"
                    % r)
        f.write("};\n")
    print(len(rows), "rows")


if __name__ == "__main__":
    main()
