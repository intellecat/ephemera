#!/usr/bin/env python3
"""Regenerate tests/eclipse_nasa_ref.h (development only) from NASA's Five
Millennium Canon catalogues (Espenak & Meeus; public domain), 1901-2100:
greatest eclipse (TD), saros, type, gamma and magnitudes; for lunar
eclipses also the phase durations.

    python3 tools/make_nasa_eclipse_reference.py [--cache DIR]
"""
import argparse
import os
import re
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = "https://eclipse.gsfc.nasa.gov/%scat5/%s.html"
MONTHS = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split()


def page(cache, kind, years):
    name = "%s%s" % (kind, years)
    path = os.path.join(cache, name + ".html")
    if not os.path.exists(path):
        with urllib.request.urlopen(URL % (kind, name), timeout=120) as r:
            open(path, "wb").write(r.read())
    text = open(path, encoding="latin-1").read()
    return [re.sub(r"<[^>]*>", "", ln).split() for ln in text.splitlines()]


def jd(y, mon, d, hms):
    """Julian day (Gregorian calendar) of a TD date and time."""
    m = MONTHS.index(mon) + 1
    h, mi, s = (int(x) for x in hms.split(":"))
    if m <= 2:
        y, m = y - 1, m + 12
    a = y // 100
    b = 2 - a + a // 4
    return (int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + d + b - 1524.5 +
            (h + mi / 60 + s / 3600) / 24)


def solar_type(t):
    base = {"T": 1, "A": 2, "H": 4, "P": 8}[t[0]]
    return base | (32 if base != 8 and t[1:2] in ("+", "-") else 0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=os.path.join(ROOT, "build", "nasa"))
    args = ap.parse_args()
    os.makedirs(args.cache, exist_ok=True)
    solar, lunar = [], []
    for years in ("1901-2000", "2001-2100"):
        for f in page(args.cache, "SE", years):
            if len(f) > 10 and re.match(r"\d{4}$", f[1]) and f[2] in MONTHS:
                # num, y, mon, d, time, dT, luna, saros, type, qle, gamma, mag
                solar.append((jd(int(f[1]), f[2], int(f[3]), f[4]), int(f[7]),
                              solar_type(f[8]), float(f[10]), float(f[11])))
        for f in page(args.cache, "LE", years):
            if len(f) > 12 and re.match(r"\d{4}$", f[1]) and f[2] in MONTHS:
                # ..., type, qse, gamma, pen mag, um mag, pen, par, total (min)
                dur = [0.0 if x == "-" else float(x) for x in f[13:16]]
                lunar.append((jd(int(f[1]), f[2], int(f[3]), f[4]), int(f[7]),
                              {"N": 16, "P": 8, "T": 1}[f[8][0]], float(f[10]),
                              float(f[11]), float(f[12])) + tuple(dur))
    with open(os.path.join(ROOT, "tests", "eclipse_nasa_ref.h"), "w") as out:
        out.write("/* Generated by tools/make_nasa_eclipse_reference.py from NASA's Five\n"
                  " * Millennium Canon (Espenak & Meeus), 1901-2100, TD.  Test data. */\n"
                  "#pragma once\n\nstruct NasaSolar { double max; int saros, type; "
                  "double gamma, mag; };\nstatic const NasaSolar kNasaSolar[] = {\n")
        for r in solar:
            out.write("    {%.6f, %d, %d, %.4f, %.4f},\n" % r)
        out.write("};\n\nstruct NasaLunar { double max; int saros, type; double gamma, "
                  "pmag, umag, pen, par, total; };\nstatic const NasaLunar kNasaLunar[] = {\n")
        for r in lunar:
            out.write("    {%.6f, %d, %d, %.4f, %.4f, %.4f, %.1f, %.1f, %.1f},\n" % r)
        out.write("};\n")
    print(len(solar), "solar,", len(lunar), "lunar")


if __name__ == "__main__":
    main()
