#!/usr/bin/env python3
"""Tabulate Delta-T = TT - UT1 (seconds) at each 1 January, 1620-2150.

Values come from Skyfield's built-in tables: IERS observed UT1 (with its
short-term predictions) from 1973, and Stephenson, Morrison & Hohenkerk
(2016) before that and for the long-term extrapolation after the IERS data
end.  Emitted to data/delta_t_data.{h,cpp}.

Development tool; needs skyfield.  Re-run occasionally to pick up new IERS
data.

    python3 tools/gen_delta_t.py
"""
import os

from skyfield.api import load

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FIRST, LAST = 1620, 2150


def main():
    ts = load.timescale()
    values = [float(ts.utc(y, 1, 1).delta_t) for y in range(FIRST, LAST + 1)]

    h = os.path.join(ROOT, "data", "delta_t_data.h")
    cpp = os.path.join(ROOT, "data", "delta_t_data.cpp")
    with open(h, "w") as f:
        f.write("/* Generated by tools/gen_delta_t.py -- do not edit. */\n")
        f.write("#pragma once\n\nnamespace eph {\nnamespace delta_t {\n\n")
        f.write(f"constexpr int kFirstYear = {FIRST};\n")
        f.write(f"constexpr int kLastYear = {LAST};\n\n")
        f.write("/* Delta-T in seconds at 1 January of each year. */\n")
        f.write("extern const float kTable[kLastYear - kFirstYear + 1];\n\n")
        f.write("}  // namespace delta_t\n}  // namespace eph\n")
    with open(cpp, "w") as f:
        f.write("/* Generated by tools/gen_delta_t.py -- do not edit. */\n")
        f.write('#include "delta_t_data.h"\n\nnamespace eph {\nnamespace delta_t {\n\n')
        f.write("const float kTable[kLastYear - kFirstYear + 1] = {\n")
        for k in range(0, len(values), 10):
            row = values[k:k + 10]
            f.write(f"    /* {FIRST + k} */ " +
                    ", ".join(f"{v:.2f}f" for v in row) + ",\n")
        f.write("};\n\n}  // namespace delta_t\n}  // namespace eph\n")
    print("wrote", h, cpp)


if __name__ == "__main__":
    main()
