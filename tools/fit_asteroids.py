#!/usr/bin/env python3
"""Fit compact Chebyshev series for Ceres, Pallas, Juno, Vesta and Chiron.

Fetches heliocentric ecliptic-J2000 positions from JPL Horizons (public
data) over 1600-2500 (the span Horizons covers for them) and packs them as adaptive-interval Chebyshev
polynomials with float32 coefficients, emitted to
data/asteroid_data.{h,cpp}.

Development tool; needs network + numpy.

    python3 tools/fit_asteroids.py
"""
from __future__ import annotations

import os
import sys
import urllib.parse
import urllib.request

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
J2000 = 2451545.0

# (C++ tag, Horizons command)
ASTEROIDS = [
    ("CERES", "1;"),
    ("PALLAS", "2;"),
    ("JUNO", "3;"),
    ("VESTA", "4;"),
    ("CHIRON", "2060;"),
]

START = "1600-01-01"
STOP = "2500-01-01"
STEP = "10 d"
DEG = 12
TARGET = 0.01  # arcsec


def horizons(cmd):
    params = {
        "format": "text", "COMMAND": f"'{cmd}'", "OBJ_DATA": "'NO'",
        "MAKE_EPHEM": "'YES'", "EPHEM_TYPE": "'VECTORS'",
        "CENTER": "'500@10'", "START_TIME": f"'{START}'",
        "STOP_TIME": f"'{STOP}'", "STEP_SIZE": f"'{STEP}'",
        "REF_PLANE": "'ECLIPTIC'", "REF_SYSTEM": "'J2000'",
        "OUT_UNITS": "'AU-D'", "VEC_TABLE": "'1'",
    }
    url = "https://ssd.jpl.nasa.gov/api/horizons.api?" + urllib.parse.urlencode(
        params)
    with urllib.request.urlopen(url, timeout=180) as r:
        text = r.read().decode("utf-8", "replace")
    i = text.find("$$SOE")
    j = text.find("$$EOE")
    lines = text[i + 5:j].strip().splitlines()
    jds, xyz = [], []
    k = 0
    while k < len(lines):
        ln = lines[k]
        if "=" in ln and "A.D." in ln:
            jds.append(float(ln.split("=")[0].strip()))
            xyz.append([float(lines[k + 1].split("=")[m].split()[0])
                        for m in (1, 2, 3)])
            k += 2
        else:
            k += 1
    return np.array(jds), np.array(xyz)


def fit_err(Y, N):
    M = len(Y)
    uu = 2.0 * np.arange(M) / (M - 1) - 1.0
    V = np.polynomial.chebyshev.chebvander(uu, N)
    C, _, _, _ = np.linalg.lstsq(V, Y, rcond=None)
    rec = V @ C
    cr = np.linalg.norm(np.cross(rec, Y), axis=1) / np.maximum(
        np.linalg.norm(rec, axis=1) * np.linalg.norm(Y, axis=1), 1e-30)
    return np.arcsin(np.clip(cr, -1, 1)).max() * 206265.0, C


def pack(jds, X, N):
    n = len(X)
    minM, maxM = N + 4, 4000
    segs = []
    maxe = 0.0
    i = 0
    while i < n - 1:
        if i + minM - 1 > n - 1:
            # Too few samples left: end the previous segment earlier so the
            # last one has the minimum length (both stay within TARGET).
            if segs:
                pi, _, _ = segs.pop()
                j = n - minM
                segs.append((pi, j, fit_err(X[pi:j + 1], N)[1]))
                segs.append((j, n - 1, fit_err(X[j:n], N)[1]))
            break
        lo, hi = i + minM - 1, min(n - 1, i + maxM - 1)
        best, bestC = None, None
        while lo <= hi:
            mid = (lo + hi) // 2
            e, C = fit_err(X[i:mid + 1], N)
            if e <= TARGET:
                best, bestC = mid, C
                lo = mid + 1
            else:
                hi = mid - 1
        if best is None:
            best, bestC = i + minM - 1, fit_err(X[i:i + minM], N)[1]
        segs.append((i, best, bestC))
        i = best
    tstart = np.array([jds[s[0]] for s in segs] + [jds[segs[-1][1]]])
    coef = np.stack([s[2].T for s in segs])  # [seg][coord][coef]
    return tstart, coef.astype(np.float32)


def emit(models):
    h = os.path.join(ROOT, "data", "asteroid_data.h")
    cpp = os.path.join(ROOT, "data", "asteroid_data.cpp")
    with open(h, "w") as f:
        f.write("/* Generated by tools/fit_asteroids.py -- do not edit. */\n")
        f.write("#pragma once\n\nnamespace eph {\nnamespace ast {\n\n")
        f.write("struct Body { const double* t; const float* c;\n"
                "              int nseg; int ncoef; };\n\n")
        f.write("extern const Body bodies[%d];\n\n" % len(models))
        f.write("}  // namespace ast\n}  // namespace eph\n")
    with open(cpp, "w") as f:
        f.write("/* Generated by tools/fit_asteroids.py -- do not edit. */\n")
        f.write('#include "asteroid_data.h"\n\nnamespace eph {\nnamespace ast {\n\n')
        for tag, (tstart, coef) in models.items():
            f.write(f"static const double {tag}_t[{len(tstart)}] = {{\n    ")
            f.write(", ".join(repr(float(x)) for x in tstart))
            f.write("\n};\n\n")
            flat = coef.reshape(-1)
            f.write(f"static const float {tag}_c[{len(flat)}] = {{\n")
            for k in range(0, len(flat), 8):
                f.write("    " + ", ".join(repr(float(x)) for x in flat[k:k + 8])
                        + ",\n")
            f.write("};\n\n")
        f.write("const Body bodies[%d] = {\n" % len(models))
        for tag, (tstart, coef) in models.items():
            f.write(f"    {{{tag}_t, {tag}_c, {len(tstart) - 1}, {coef.shape[2]}}},\n")
        f.write("};\n\n}  // namespace ast\n}  // namespace eph\n")
    return h, cpp


def main():
    models = {}
    for tag, cmd in ASTEROIDS:
        jds, xyz = horizons(cmd)
        tstart, coef = pack(jds, xyz, DEG)
        # held-out check: fit error at the segment midpoints
        maxe = 0.0
        for si in range(len(tstart) - 1):
            m = (jds >= tstart[si]) & (jds <= tstart[si + 1])
            if m.sum() < 2:
                continue
            u = (2 * jds[m] - (tstart[si] + tstart[si + 1])) / (tstart[si + 1] - tstart[si])
            V = np.polynomial.chebyshev.chebvander(u, DEG)
            rec = V @ coef[si].T
            Y = xyz[m]
            cr = np.linalg.norm(np.cross(rec, Y), axis=1) / np.maximum(
                np.linalg.norm(rec, axis=1) * np.linalg.norm(Y, axis=1), 1e-30)
            maxe = max(maxe, np.arcsin(np.clip(cr, -1, 1)).max() * 206265.0)
        models[tag] = (tstart, coef)
        sys.stderr.write(f"{tag}: {len(tstart)-1} seg, {len(coef.reshape(-1))*4/1e6:.2f} MB, "
                         f"err<={maxe:.4f}\"\n")
    emit(models)


if __name__ == "__main__":
    main()
