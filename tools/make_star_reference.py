#!/usr/bin/env python3
"""Regenerate tests/stars_ref.h (development only): apparent ecliptic
positions of date for a sample of catalogue stars, propagated with ERFA's
pmsafe (rigorous space motion) and reduced with Skyfield and DE440.  Uses
the catalogue in data/stars_data.cpp, so it tests the computation, not the
catalogue.

    python3 tools/make_star_reference.py
"""
import math
import os
import re

import erfa
import numpy as np
from skyfield.api import Star, load
from skyfield.framelib import ecliptic_frame
from skyfield.units import Angle

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    src = open(os.path.join(ROOT, "data", "stars_data.cpp")).read()
    rows = re.findall(r'\{"([^"]+)", "([^"]*)", (\d+), ([-\d.]+)f, ([-\d.]+), '
                      r'([-\d.]+), ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f\}', src)
    ts = load.timescale()
    eph = load(os.path.join(ROOT, "de440.bsp"))
    earth = eph["earth"]
    mas = math.radians(1 / 3.6e6)
    rng = np.random.default_rng(3)
    # The fastest-moving stars and a random sample, 1600-2500.
    fast = sorted(range(len(rows)), key=lambda i: -math.hypot(float(rows[i][6]),
                                                             float(rows[i][7])))[:6]
    sample = fast + list(rng.choice(len(rows), 40, replace=False))
    out = []
    for k in sample:
        name, _, _, _, ra, dec, pmr, pmd, plx, rv = rows[k]
        ra, dec, pmr, pmd, plx, rv = map(float, (ra, dec, pmr, pmd, plx, rv))
        jd = float(rng.uniform(2305448.0, 2634000.0))
        t = ts.tt_jd(jd)
        r2, d2, _, _, px2, _ = erfa.pmsafe(ra, dec, pmr * mas / math.cos(dec),
                                           pmd * mas, plx / 1000.0, rv,
                                           2451545.0, 0.0, jd, 0.0)
        star = Star(ra=Angle(radians=float(r2)), dec=Angle(radians=float(d2)),
                    parallax_mas=float(px2) * 1000.0, epoch=t)
        lat, lon, _ = earth.at(t).observe(star).apparent().frame_latlon(ecliptic_frame)
        out.append((name, jd, lon.degrees, lat.degrees))
    path = os.path.join(ROOT, "tests", "stars_ref.h")
    with open(path, "w") as f:
        f.write("/* Generated by tools/make_star_reference.py: apparent ecliptic "
                "of date\n * (degrees), ERFA pmsafe + Skyfield/DE440. */\n")
        f.write("#pragma once\nstruct StarRef { const char* name; double jd_tt, "
                "lon, lat; };\n\n")
        f.write("static const StarRef kStarRef[%d] = {\n" % len(out))
        for r in out:
            f.write('    {"%s", %.6f, %.10f, %.10f},\n' % r)
        f.write("};\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
