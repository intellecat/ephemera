#!/usr/bin/env python3
"""Regenerate tests/stars_ref.h (development only): apparent ecliptic
positions of date for a sample of catalogue stars, propagated with ERFA's
pmsafe (rigorous space motion) and reduced with Skyfield and DE440.  Uses
the catalogue in data/stars_data.cpp, so it tests the computation, not the
catalogue.

Also the star-based ayanamsas from their definitions: the star's apparent
longitude of date (as above) minus the nutation in longitude (ERFA,
IAU 2000A) minus the longitude the system assigns to it.

    python3 tools/make_star_reference.py      (DE440=path/to/de440.bsp)
"""
import math
import os
import re

import erfa
import numpy as np
from skyfield.api import Star, load
from skyfield.framelib import ecliptic_frame
from skyfield.units import Angle

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Star-based ayanamsas in eph_ayanamsa_system order: (HIP, 0 for the
# Galactic Center; defining sidereal longitude, degrees).
STAR_AYANAMSAS = [(65474, 180.0), (5737, 359.0 + 50.0 / 60.0), (42911, 106.0),
                  (85927, 240.0), (0, 240.0), (0, 244.376973), (0, 270.0)]
AYANAMSA_DATES = [2305448.0, 2415020.5, 2451545.0, 2469807.5, 2634000.0]


def apparent(row, jd, ts, earth):
    """Apparent ecliptic longitude, latitude of date (degrees)."""
    mas = math.radians(1 / 3.6e6)
    ra, dec, pmr, pmd, plx, rv = map(float, row[4:10])
    t = ts.tt_jd(jd)
    r2, d2, _, _, px2, _ = erfa.pmsafe(ra, dec, pmr * mas / math.cos(dec),
                                       pmd * mas, plx / 1000.0, rv,
                                       2451545.0, 0.0, jd, 0.0)
    star = Star(ra=Angle(radians=float(r2)), dec=Angle(radians=float(d2)),
                parallax_mas=float(px2) * 1000.0, epoch=t)
    lat, lon, _ = earth.at(t).observe(star).apparent().frame_latlon(ecliptic_frame)
    return lon.degrees, lat.degrees


def main():
    src = open(os.path.join(ROOT, "data", "stars_data.cpp")).read()
    rows = re.findall(r'\{"([^"]+)", "([^"]*)", (\d+), ([-\d.]+)f, ([-\d.]+), '
                      r'([-\d.]+), ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f, ([-\d.]+)f\}', src)
    ts = load.timescale()
    eph = load(os.environ.get("DE440", os.path.join(ROOT, "de440.bsp")))
    earth = eph["earth"]
    rng = np.random.default_rng(3)
    # The fastest-moving stars and a random sample, 1600-2500.
    fast = sorted(range(len(rows)), key=lambda i: -math.hypot(float(rows[i][6]),
                                                             float(rows[i][7])))[:6]
    sample = fast + list(rng.choice(len(rows), 40, replace=False))
    out = []
    for k in sample:
        jd = float(rng.uniform(2305448.0, 2634000.0))
        out.append((rows[k][0], jd) + apparent(rows[k], jd, ts, earth))
    by_hip = {int(r[2]): r for r in rows}
    ayanamsas = []
    for hip, lon0 in STAR_AYANAMSAS:
        vals = []
        for jd in AYANAMSA_DATES:
            lon, _ = apparent(by_hip[hip], jd, ts, earth)
            dpsi, _ = erfa.nut06a(jd, 0.0)
            vals.append((lon - math.degrees(dpsi) - lon0 + 180.0) % 360.0 - 180.0)
        ayanamsas.append(vals)
    path = os.path.join(ROOT, "tests", "stars_ref.h")
    with open(path, "w") as f:
        f.write("/* Generated by tools/make_star_reference.py: apparent ecliptic "
                "of date\n * (degrees), ERFA pmsafe + Skyfield/DE440. */\n")
        f.write("#pragma once\nstruct StarRef { const char* name; double jd_tt, "
                "lon, lat; };\n\n")
        f.write("static const StarRef kStarRef[%d] = {\n" % len(out))
        for r in out:
            f.write('    {"%s", %.6f, %.10f, %.10f},\n' % r)
        f.write("};\n\n/* Star-based ayanamsas (degrees) from their definitions, in\n"
                " * eph_ayanamsa_system order from EPH_AYANAMSA_TRUE_CITRA. */\n")
        f.write("static const double kStarAyanamsaDates[%d] = {%s};\n"
                % (len(AYANAMSA_DATES), ", ".join("%.1f" % d for d in AYANAMSA_DATES)))
        f.write("static const double kStarAyanamsaRef[%d][%d] = {\n"
                % (len(ayanamsas), len(AYANAMSA_DATES)))
        for v in ayanamsas:
            f.write("    {%s},\n" % ", ".join("%.10f" % x for x in v))
        f.write("};\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
