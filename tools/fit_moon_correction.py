#!/usr/bin/env python3
"""Fit a DE440s correction for the Moon.

ELP2000-82B is fitted to DE200/LE200, so the Moon drifts from DE440 by
~1.2 arcsec/century away from J2000 (up to ~2.8" at the 1850/2140 edges).
This tool samples the residual of the *engine's* (truncated) Moon and fits
a Chebyshev polynomial in T, emitted to data/corr_moon.cpp.

The model is taken from the built library (build/libephemeris.a), so run
`make` first.  Requires numpy, skyfield and pyerfa.

    make
    /tmp/eph/bin/python tools/fit_moon_correction.py
"""
from __future__ import annotations

import math
import os
import subprocess
import sys
import tempfile

import erfa
import numpy as np
from skyfield.api import load

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
J2000 = 2451545.0
DEGREE = 40

PROBE = r"""
#include "ephemeris/ephemeris.h"
#include <cstdio>
static const double R2D = 180.0 / 3.14159265358979323846;
int main() {
    double jd;
    while (scanf("%lf", &jd) == 1) {
        eph_position p;
        eph_position_tt(EPH_MOON, jd, &p);
        printf("%.12f %.12f %.15f\n", p.longitude * R2D,
               p.latitude * R2D, p.distance);
    }
    return 0;
}
"""


def model_moon(jds):
    lib = os.path.join(ROOT, "build", "libephemeris.a")
    if not os.path.exists(lib):
        sys.exit("build/libephemeris.a missing; run `make` first")
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "probe.cpp")
        exe = os.path.join(d, "probe")
        with open(src, "w") as f:
            f.write(PROBE)
        subprocess.run(["g++", "-std=c++17", "-O2", "-I",
                        os.path.join(ROOT, "include"), src, lib, "-lm",
                        "-o", exe], check=True)
        inp = "\n".join(f"{x:.9f}" for x in jds)
        out = subprocess.run([exe], input=inp, capture_output=True,
                             text=True, check=True).stdout.strip().split("\n")
    a = np.array([[float(x) for x in line.split()] for line in out])
    return np.radians(a[:, 0]), np.radians(a[:, 1]), a[:, 2]


def de440s_moon(jds):
    eph = load("de440s.bsp")
    ts = load.timescale()
    earth = eph["earth"]
    moon = eph["moon"]
    t = ts.tt_jd(jds)
    h = moon.at(t) - earth.at(t)
    ra, dec, dist = h.radec()  # ICRS
    ra = np.asarray(ra.radians)
    dec = np.asarray(dec.radians)
    r = np.asarray(dist.au)
    v = np.array([np.cos(dec) * np.cos(ra),
                  np.cos(dec) * np.sin(ra),
                  np.sin(dec)])
    lon = np.empty(len(jds))
    lat = np.empty(len(jds))
    for k, jd in enumerate(jds):
        dt = jd - J2000
        vd = erfa.pmat76(J2000, dt) @ v[:, k]
        eps = erfa.obl80(J2000, dt)
        y = vd[1] * math.cos(eps) + vd[2] * math.sin(eps)
        z = -vd[1] * math.sin(eps) + vd[2] * math.cos(eps)
        lon[k] = math.atan2(y, vd[0])
        lat[k] = math.asin(z)
    return lon, lat, r


def main():
    ts = load.timescale()
    jds = np.arange(float(ts.utc(1850, 1, 1).tt),
                    float(ts.utc(2140, 1, 1).tt), 5.0)
    T = (jds - J2000) / 36525.0
    tmin, tmax = float(T.min()), float(T.max())
    u = (2.0 * T - (tmin + tmax)) / (tmax - tmin)
    V = np.polynomial.chebyshev.chebvander(u, DEGREE)

    mlon, mlat, mr = model_moon(jds)
    dlon, dlat, dr = de440s_moon(jds)
    dlon = (dlon - mlon + math.pi) % (2 * math.pi) - math.pi
    dlat = dlat - mlat
    dr = dr - mr

    train = np.zeros(len(T), bool)
    train[::2] = True
    test = ~train
    coefs = {}
    for name, target, unit in (("lon", dlon, 3600.0), ("lat", dlat, 3600.0),
                               ("rad", dr, 1.0)):
        c, _, _, _ = np.linalg.lstsq(V[train], target[train], rcond=None)
        tr = np.abs(V[train] @ c - target[train]).max()
        te = np.abs(V[test] @ c - target[test]).max()
        print(f"moon {name}: train {tr*unit:8.4f} test {te*unit:8.4f} "
              f"{'\"' if name != 'rad' else 'AU'}")
        coefs[name] = c

    emit(coefs, tmin, tmax)


def c_float(x):
    return f"{x:.17g}"


def emit(coefs, tmin, tmax):
    cpp = os.path.join(ROOT, "data", "corr_moon.cpp")
    n = DEGREE + 1
    with open(cpp, "w") as f:
        f.write("/* Generated by tools/fit_moon_correction.py -- do not edit. */\n")
        f.write('#include "corr_data.h"\n\nnamespace eph {\nnamespace corr {\n\n')
        for name in ("lon", "lat", "rad"):
            f.write(f"static const double MOON_{name}[{n}] = {{\n    ")
            f.write(", ".join(c_float(x) for x in coefs[name]))
            f.write("\n};\n\n")
        f.write(f"const Series moon = {{{c_float(tmin)}, {c_float(tmax)}, "
                f"MOON_lon, MOON_lat, MOON_rad, {n}}};\n")
        f.write("\n}  // namespace corr\n}  // namespace eph\n")
    sys.stderr.write(f"wrote {cpp}\n")


if __name__ == "__main__":
    main()
