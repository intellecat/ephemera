#ifndef EPH_DATA_H
#define EPH_DATA_H

/* Series and tables loaded from data files (src/data.cpp).
 *
 * The coefficient structures are those of the data/ headers; their arrays
 * point into the loaded file buffers.  Each set is null/zero when no
 * loaded file provides it. */

#include <cstddef>
#include <cstdint>

#include "../data/asteroid_data.h"
#include "../data/corr_data.h"
#include "../data/elp_data.h"
#include "../data/pluto_data.h"
#include "../data/vsop87d_data.h"

namespace eph {

/* Container format (little-endian):
 *   0  "EPHD", u32 version (2), u32 section count,
 *      u32 CRC-32 (zlib) of everything from byte 16 on
 *  16  sections: u32 type, u32 id, u64 offset, u64 size  (24 bytes each)
 * Section payloads start at 8-byte aligned offsets. */
enum SectionType {
    kSectionVsop = 1,       /* id: planet | role << 8  */
    kSectionElp = 2,        /* id: role << 8           */
    kSectionPluto = 3,      /* Pluto fit               */
    kSectionCorrection = 4, /* id: planet, or 10 (Moon) */
    kSectionAsteroid = 5,   /* id: 0..4 (Ceres..Chiron) */
    kSectionTable = 6,      /* DE440 residual table    */
    kSectionInfo = 7,       /* free text               */
    kSectionStars = 8,      /* fixed-star catalogue    */
};

/* Series role: the theory used for analytical positions, or the truncated
 * base under a residual table. */
enum Role { kTheory = 0, kBase = 1 };

struct SeriesSet {
    bool vsop_ok[8];
    vsop87d::Body vsop[8];
    vsop87d::Series vsop_series[8][3][6];
    bool elp_ok;
    elp::Coord elp[3];
};

constexpr int kMaxTables = 32;

/* A fixed star in the star section: ICRS position at J2000.0 (radians),
 * proper motion (mas/yr, RA as dRA/dt cos dec), parallax (mas), radial
 * velocity (km/s), V magnitude, Hipparcos number, and offsets of its
 * name and designation in the section's string pool (NUL-terminated). */
struct StarRecord {
    double ra, dec;
    float pm_ra, pm_dec, parallax, rv, vmag;
    uint32_t hip, name, designation;
};
static_assert(sizeof(StarRecord) == 48, "StarRecord layout");
constexpr int kAsteroids = 5; /* Ceres, Pallas, Juno, Vesta, Chiron */

struct Data {
    SeriesSet set[2]; /* indexed by Role */
    bool pluto_ok;
    pluto_fit::Body pluto;
    bool corr_ok[11];
    corr::Series corr[11];
    bool asteroid_ok[kAsteroids];
    ast::Body asteroid[kAsteroids];
    /* Residual table sections, in load order (later ones take
     * precedence). */
    struct {
        const unsigned char* p;
        uint64_t size;
    } tables[kMaxTables];
    /* Fixed stars: records and their string pool. */
    const StarRecord* stars;
    int nstars;
    const char* star_strings;
    uint64_t star_strings_size;
    int ntables;
    /* CRC-32 of the base series sections in effect (see compressed.cpp). */
    const unsigned char* base_section[9]; /* VSOP Mercury..Neptune, ELP */
    uint64_t base_size[9];
    uint32_t base_crc;
};

/* The current data (rebuilt on every load/unload). */
const Data& data();

/* Changes on every load/unload. */
int data_generation();

/* The data file compiled into the library, if any (src/embedded_none.cpp
 * or one generated by tools/embed.cmake).  False when there is none. */
bool embedded_data(const unsigned char*& p, size_t& size);

/* Residual tables (src/compressed.cpp): parse the tables in data().
 * Returns false if one is malformed or its base series are missing or are
 * not the ones it was made against. */
bool tables_attach();

}  // namespace eph

#endif
