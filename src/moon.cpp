void moon_position(double jd_tt, double& lon, double& lat, double& dist_au) {
    const double T = (jd_tt - J2000) / DAYS_PER_CENTURY;

    const double cLp[] = {218.3164477, 481267.88123421, -0.0015786,
                          1.0 / 538841.0, -1.0 / 65194000.0};
    const double cD[] = {297.8501921, 445267.1114034, -0.0018819,
                         1.0 / 545868.0, -1.0 / 113065000.0};
    const double cM[] = {357.5291092, 35999.0502909, -0.0001535,
                         1.0 / 24490000.0};
    const double cMp[] = {134.9633964, 477198.8675055, 0.0087414,
                          1.0 / 69699.0, -1.0 / 14712000.0};
    const double cF[] = {93.272095, 483202.0175233, -0.0036539,
                         -1.0 / 3526000.0, 1.0 / 863310000.0};
    const double cE[] = {1.0, -0.002516, -0.0000074};

    const double Lp = horner(T, cLp, 5) * DEG;
    const double D = horner(T, cD, 5) * DEG;
    const double M = horner(T, cM, 4) * DEG;
    const double Mp = horner(T, cMp, 5) * DEG;
    const double F = horner(T, cF, 5) * DEG;
    const double E = horner(T, cE, 3);

    const double A1 = (119.75 + 131.849 * T) * DEG;
    const double A2 = (53.09 + 479264.29 * T) * DEG;
    const double A3 = (313.45 + 481266.484 * T) * DEG;

    double sum_l = 3958.0 * std::sin(A1) + 1962.0 * std::sin(Lp - F) +
                   318.0 * std::sin(A2);
    double sum_r = 0.0;
    double sum_b = -2235.0 * std::sin(Lp) + 382.0 * std::sin(A3) +
                   175.0 * std::sin(A1 - F) + 175.0 * std::sin(A1 + F) +
                   127.0 * std::sin(Lp - Mp) - 115.0 * std::sin(Lp + Mp);

    for (const MoonTermL& t : kTermsL) {
        const double arg = t.d * D + t.m * M + t.n * Mp + t.f * F;
        double e = 1.0;
        if (t.m == 1 || t.m == -1)
            e = E;
        else if (t.m == 2 || t.m == -2)
            e = E * E;
        sum_l += t.l * std::sin(arg) * e;
        sum_r += t.r * std::cos(arg) * e;
    }
    for (const MoonTermB& t : kTermsB) {
        const double arg = t.d * D + t.m * M + t.n * Mp + t.f * F;
        double e = 1.0;
        if (t.m == 1 || t.m == -1)
            e = E;
        else if (t.m == 2 || t.m == -2)
            e = E * E;
        sum_b += t.b * std::sin(arg) * e;
    }

    lon = normalize(Lp + sum_l * 1e-6 * DEG);
    lat = sum_b * 1e-6 * DEG;
    dist_au = (385000.56 + sum_r * 1e-3) / AU_KM;
}

